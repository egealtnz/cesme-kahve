// Bundles each edge function (plus its ../_shared helpers) into ONE file, for deploying through the
// Supabase dashboard editor (Edge Functions → Deploy a new function → Via Editor) when the Supabase CLI
// isn't available. With the CLI, use `supabase functions deploy` instead; it needs no bundling.
//   node scripts/bundle-functions.mjs   → dist-functions/<name>.ts
import { build } from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const src = path.join(root, 'supabase/functions');
const out = path.join(root, 'dist-functions');
fs.mkdirSync(out, { recursive: true });

for (const name of fs.readdirSync(src).filter((d) => !d.startsWith('_') && fs.existsSync(path.join(src, d, 'index.ts')))) {
  await build({
    entryPoints: [path.join(src, name, 'index.ts')],
    outfile: path.join(out, `${name}.ts`),
    bundle: true, format: 'esm', platform: 'neutral', target: 'es2022',
    external: ['npm:*', 'jsr:*'],
    supported: { 'template-literal': false },   // plain strings: easier to paste into the dashboard editor
    banner: { js: `// ${name} — generated by scripts/bundle-functions.mjs from supabase/functions/${name}/ (edit those, not this file)` },
    logLevel: 'warning',
  });
  console.log(`dist-functions/${name}.ts`);
}
